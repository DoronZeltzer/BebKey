# ── De-duplicate (some Hebrew names mapped twice to the same Yad2 ID) ────────
def _dedupe(cities: list[City]) -> list[City]:
    seen: set[str] = set()
    result: list[City] = []
    for c in cities:
        if c.hebrew in seen:
            continue
        seen.add(c.hebrew)
        result.append(c)
    return result

ALL_CITIES = _dedupe(ALL_CITIES)


# ── Convenience views ────────────────────────────────────────────────────────
def hebrew_names() -> list[str]:
    """Just the Hebrew names - for Facebook / text-search scrapers."""
    return [c.hebrew for c in ALL_CITIES]


def english_names() -> list[str]:
    """Transliterated English names - for English-language sources (Janglo, Anglo)."""
    return [c.english for c in ALL_CITIES]


def yad2_tuples() -> list[tuple]:
    """
    Returns Yad2-compatible (name, city_id, area_id, region_id) tuples.
    Skips any city with yad2_city_id == 0.
    """
    return [
        (c.hebrew, c.yad2_city_id, c.yad2_area_id, c.yad2_region_id)
        for c in ALL_CITIES
        if c.yad2_city_id > 0
    ]


def top_cities(n: int = 50) -> list[City]:
    """First N cities (roughly population-sorted) - for cost-sensitive scrapers."""
    return ALL_CITIES[:n]


